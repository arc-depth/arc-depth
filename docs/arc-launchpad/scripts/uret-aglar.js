"use strict";
/* ===========================================================================
 * uret-aglar.js — writes docs/js/aglar.js from the deployment records
 *
 *   node scripts/uret-aglar.js
 *
 * The interface's chain list is generated, never typed: every address comes
 * from dagitim-ag.json / dagitim-pulse2.json / dagitim-robinhood.json and
 * zincirler.js, the same files the deployment audit checks against chain.
 * =========================================================================== */
const fs = require("fs");
const path = require("path");
const { getAddress } = require("ethers");
const { EVM, IKIZ_SECENEK } = require("./zincirler");

const KOK = path.join(__dirname, "..");
const oku = (f) => JSON.parse(fs.readFileSync(path.join(KOK, f), "utf8"));
const AG = oku("dagitim-ag.json");
const P2 = oku("dagitim-pulse2.json").arc;
const RH = oku("dagitim-robinhood.json").robinhood;
const N2 = fs.existsSync(path.join(KOK, "dagitim-nesil2.json")) ? oku("dagitim-nesil2.json") : { ev: {}, uzak: {} };
const N3 = fs.existsSync(path.join(KOK, "dagitim-nesil3.json")) ? oku("dagitim-nesil3.json") : {};
const DOMAIN = { arc: 26, robinhood: 35, base: 6, arbitrum: 3, ethereum: 0, avalanche: 1, monad: 15, hyperevm: 19, bsc: 17 };
const HAVUZ_AG = fs.existsSync(path.join(KOK, "dagitim-ikiz-havuz-ag.json")) ? oku("dagitim-ikiz-havuz-ag.json") : {};
const FTHM_AG = fs.existsSync(path.join(KOK, "dagitim-fthm-ag.json")) ? oku("dagitim-fthm-ag.json") : {};
const A = (x) => getAddress(String(x).toLowerCase());

const KASIF = { arc: "https://explorer.arc.io", robinhood: "https://robin.etherscan.io", base: "https://basescan.org",
  arbitrum: "https://arbiscan.io", ethereum: "https://etherscan.io", bsc: "https://bscscan.com",
  avalanche: "https://snowscan.xyz", monad: "https://monadvision.com", hyperevm: "https://hyperevmscan.io" };
const GAZ = { arc: "USDC", robinhood: "ETH", base: "ETH", arbitrum: "ETH", ethereum: "ETH", bsc: "BNB",
  avalanche: "AVAX", monad: "MON", hyperevm: "HYPE" };

const aglar = Object.entries(EVM).map(([ad, z]) => {
  const o = {
    anahtar: ad, ad: z.ad, id: z.chainId, eid: z.eid, rpc: z.rpc, gaz: GAZ[ad], kasif: KASIF[ad],
    launchpad: A(ad === "arc" ? P2.launchpad : ad === "robinhood" ? RH.launchpad : AG[ad].PulseLaunchpad),
    quote: A(ad === "arc" ? P2.quote : ad === "robinhood" ? RH.quote : AG[ad].quote),
    dolar: A(z.dolar.adres), dolarSembol: z.dolar.sembol,
  };
  if (AG[ad] && AG[ad].Dolar6) o.sarmal = A(AG[ad].Dolar6);
  o.domain = DOMAIN[ad];
  if (N2.ev[ad]) {
    /* Second generation: the founder chooses where the collateral goes
       (one of uzaklar) or keeps it in dollars here. */
    o.nesil = 2;
    o.launchpad1 = o.launchpad;
    o.launchpad = A(N2.ev[ad].PulseLaunchpad2);
    o.quote = A(N2.ev[ad].quote);
    o.dolar = o.quote;
    o.dolarSembol = "USDC";
    delete o.sarmal;
    o.uzaklar = Object.keys(N2.ev[ad].uzaklar || {});
  } else o.nesil = 1;
  if (N3[ad] && N3[ad].PulseLaunchpad3) {
    /* Local collateral (nesil 3): the founder pastes any token on this
       chain; the launch converts the collateral into it. This is the
       launchpad the app uses wherever it exists. */
    o.nesil = 3;
    o.launchpad2 = o.launchpad;
    o.launchpad = A(N3[ad].PulseLaunchpad3);
    o.quote = A(N3[ad].quote);
    /* BNB keeps its wrapper: dolar is the 18-decimal USDC people hold,
       sarmal the 6-decimal pUSDC the launchpad takes */
    if (!o.sarmal) { o.dolar = o.quote; o.dolarSembol = ad === "robinhood" ? "USDG" : "USDC"; }
    o.poolManager = A(N3[ad].poolManager);
    /* The audited SwapRouter the terminal trades through; null until
       scripts/dagit-router-ag.js has put it on this chain, and the
       terminal then says so instead of offering a button. */
    o.takasRouter = N3[ad].SwapRouter ? A(N3[ad].SwapRouter) : null;
  }
  if (HAVUZ_AG[ad]) { o.ikizHavuzFabrika = A(HAVUZ_AG[ad].fabrika); o.ikizHook = A(HAVUZ_AG[ad].hook); }
  return o;
});

const metin = `/* ===========================================================================
 * aglar.js — the nine EVM chains ARC PULSE runs on, for the interface
 *
 * GENERATED by scripts/uret-aglar.js from the deployment records; do not
 * edit by hand. Checked against the chain by scripts/denetim-dagitim-ag.js.
 *
 * One launchpad per chain, the same audited bytecode, each with that chain's
 * own dollar: USDC wherever Circle issues it, USDG on Robinhood, and on BNB a
 * 1:1 six-decimal wrapper (Dolar6, "pUSDC") over the 18-decimal Binance-Peg
 * USDC — \`sarmal\` names it, and the create flow wraps before it launches.
 *
 *   quote   what the launchpad takes (approve this)
 *   nesil   3 where PulseLaunchpad3 is deployed (local collateral: paste a
 *           token's address, the launch converts the collateral into it);
 *           2 where PulseLaunchpad2 is deployed: launch(ad, sembol,
 *           hedefDomain, hedefVarlik, ...) and the collateral may be
 *           converted on one of "uzaklar" (CCTP V2, dagitim-nesil2.json);
 *           1 elsewhere, collateral stays the chain's dollar
 *   dolar   the chain's dollar as people hold it
 *   poolManager / takasRouter   (nesil 3) Uniswap v4 and the audited
 *           SwapRouter the terminal trades a launch pool through
 *   ikizHavuzFabrika / ikizHook   where a spread token's twin gets its pool
 *           on this chain (opened against the home price, liquidity locked)
 * =========================================================================== */

export const AGLAR = ${JSON.stringify(aglar, null, 2)};

/* One address on all nine chains (Arachnid CREATE2, identical init code). */
export const AG = ${JSON.stringify({
    yayici: A(AG.arc.IkizYayici), fiyatAgi: A(AG.arc.FiyatAgi),
    ikizFabrika: A(AG.arc.IkizFabrikaAg), ikizOftFabrika: A(AG.arc.IkizOFTFabrikaAg),
    kapi: A(AG.arc.KapiAg), fthmIkiz: FTHM_AG.fthmIkiz ? A(FTHM_AG.fthmIkiz) : null,
  }, null, 2)};

/* lzReceive gas for a message that deploys a twin: 4.375M ran out of gas on
   Base on 14 Oct 2026 (the deployment needs ~4.58M); 6M is the measured safe
   value. LayerZero type-3 options, executor lzReceive. */
export const IKIZ_SECENEK = "${IKIZ_SECENEK}";

export const agBul = (anahtarYaDaId) =>
  AGLAR.find((a) => a.anahtar === anahtarYaDaId || a.id === Number(anahtarYaDaId)) || null;
`;
fs.writeFileSync(path.join(KOK, "docs", "js", "aglar.js"), metin);
console.log("docs/js/aglar.js: " + aglar.length + " zincir");
